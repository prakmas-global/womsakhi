/**
 * The icons this app actually draws — all 218 of them.
 *
 * Every screen did `import * as Icons from "lucide-react"` and then looked an
 * icon up by name (`Icons[n]`). A namespace import read dynamically cannot be
 * tree-shaken: the bundler has no way to know which of lucide's 5,975 icons a
 * runtime string will ask for, so it keeps all of them. Across 89 files that
 * produced fifteen separate 780 KB chunks — about 11.7 MB of icons, of which
 * the app uses 2.6%.
 *
 * Named imports shake. This module re-exports the ones we use, so call sites
 * keep working unchanged — `Icons.Wallet` and `Icons[name]` both still
 * resolve — while the bundle carries 157 icons instead of 5,975.
 *
 * Adding an icon: import it here too, or it will not render.
 */
